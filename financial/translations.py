DEFAULT_LANG = "en"


def get_translation(lang_code: str | None) -> Tuple[Dict[str, str], str]:
    """
    Resolve the active language and return (translations_for_lang, lang_code).
    Falls back to DEFAULT_LANG if the requested code is not supported.
    """
    if not lang_code:
        lang_code = DEFAULT_LANG
    lang_code = lang_code.lower()
    if lang_code not in translations:
        lang_code = DEFAULT_LANG
    return translations[lang_code], lang_code

